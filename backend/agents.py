def _match_worker_rate(role_name: str, workers: List[Dict[str, Any]]) -> float:
    """Finds the real hourly billing_rate for the closest-matching role in the Workers directory.
    Falls back to the average rate across the roster, then to a generic $100/hr if no worker data exists at all."""
    role_lower = (role_name or "").lower()

    for w in workers:
        w_role = (w.get("role") or "").lower()
        if w_role and (w_role in role_lower or role_lower in w_role):
            return float(w.get("billing_rate", 100.0))

    for w in workers:
        w_role = (w.get("role") or "").lower()
        if any(tok in role_lower for tok in w_role.split() if len(tok) > 3):
            return float(w.get("billing_rate", 100.0))

    if workers:
        return sum(float(w.get("billing_rate", 100.0)) for w in workers) / len(workers)
    return 100.0

# Per Dheeraj (stakeholder review): SOW-based bids "surely drift" and warrant a change-request contingency
# floor of ~20-25% regardless of what the risk register alone computes; staff-augmentation bids follow a
# clearly-specified brief with minimal ambiguity, so no floor is warranted beyond the risk-driven number.
_ENGAGEMENT_TYPE_CONTINGENCY_FLOOR = {
    "sow-based": 0.20,
    "hybrid": 0.10,
    "staff augmentation": 0.0,
}

def _compute_risk_buffer_rate(risks: Dict[str, Any], engagement_type: str = None) -> Dict[str, Any]:
    """Derives a contingency percentage the way a bid manager actually does it: for EACH risk,
    contingency contribution = probability% x impact% (expected value of that risk), summed across
    all risks — not a flat markup, and not a categorical severity x probability lookup. A '20% chance
    of a 20% scope increase' contributes 4%, not 20%. Also applies an engagement-type floor, since
    SOW-based bids structurally carry more change-request risk than staff-augmentation bids."""
    risk_items = risks.get("risks", []) if isinstance(risks, dict) else (risks if isinstance(risks, list) else [])

    level_to_percent = {"low": 15, "medium": 40, "high": 70}

    per_risk_contributions = []
    computed_rate = 0.0
    if risk_items:
        for r in risk_items:
            prob_pct = r.get("probability_percent")
            impact_pct = r.get("impact_percent")
            if prob_pct is None:
                prob_pct = level_to_percent.get(str(r.get("probability", "medium")).lower(), 40)
            if impact_pct is None:
                impact_pct = level_to_percent.get(str(r.get("severity", "medium")).lower(), 40)
            contribution = (float(prob_pct) / 100.0) * (float(impact_pct) / 100.0)
            per_risk_contributions.append({
                "risk_name": r.get("risk_name", "Unnamed risk"),
                "probability_percent": prob_pct,
                "impact_percent": impact_pct,
                "contribution_percent": round(contribution * 100, 2)
            })
            computed_rate += contribution
        # Cap the summed expected value at 35% — beyond that the bid itself should probably be
        # re-scoped or flagged for qualification review, not just priced with an ever-larger buffer.
        computed_rate = min(computed_rate, 0.35)

    floor = _ENGAGEMENT_TYPE_CONTINGENCY_FLOOR.get(str(engagement_type or "").strip().lower(), None)

    if not risk_items and floor is None:
        return {"rate": 0.10, "basis": "No risk analysis available — used a conservative 10% baseline.", "per_risk": []}

    rate = computed_rate
    basis_parts = []
    if risk_items:
        basis_parts.append(
            f"Computed as sum(probability% x impact%) across {len(risk_items)} identified risk(s) = {round(computed_rate * 100, 2)}%."
        )
    if floor is not None and floor > rate:
        basis_parts.append(f"Raised to the {round(floor * 100)}% floor for '{engagement_type}' engagements (change-request risk).")
        rate = floor
    elif floor is not None:
        basis_parts.append(f"Already above the {round(floor * 100)}% floor for '{engagement_type}' engagements.")

    return {
        "rate": round(rate, 4),
        "basis": " ".join(basis_parts) if basis_parts else "No risk analysis available — used a conservative 10% baseline.",
        "per_risk": per_risk_contributions
    }

