BEDROCK_MODEL_ID = os.getenv("BEDROCK_MODEL_ID", "global.anthropic.claude-haiku-4-5-20251001-v1:0")
bedrock_client = None

def _init_bedrock_client():
    """Lazily (re)creates the boto3 bedrock-runtime client from current env vars."""
    global bedrock_client
    try:
        import boto3
        bedrock_client = boto3.client(
            "bedrock-runtime",
            region_name=os.getenv("AWS_REGION", "us-east-1"),
            aws_access_key_id=os.getenv("AWS_ACCESS_KEY_ID"),
            aws_secret_access_key=os.getenv("AWS_SECRET_ACCESS_KEY"),
        )
        print("AWS Bedrock client configured successfully.")
    except Exception as e:
        bedrock_client = None
        print(f"Error configuring AWS Bedrock client: {e}")
    return bedrock_client

if os.getenv("AWS_ACCESS_KEY_ID") and os.getenv("AWS_SECRET_ACCESS_KEY"):
    _init_bedrock_client()
else:
    print("WARNING: AWS Bedrock credentials not set. Running in simulation mode with mock data.")

def is_api_key_valid() -> bool:
    """Check if valid AWS Bedrock credentials are present."""
    return bool(os.getenv("AWS_ACCESS_KEY_ID")) and bool(os.getenv("AWS_SECRET_ACCESS_KEY"))

SIMULATION_NOTICE = (
    "One or more sections could not be generated by the AI (the API call failed or no key was configured), "
    "so offline placeholder data is shown instead. These figures are illustrative, not a real analysis of your document."
)

def compute_simulation_status(*stage_outputs: Dict[str, Any]) -> Dict[str, Any]:
    """Inspects a set of agent outputs and reports whether any of them are fallback/simulated data."""
    simulated_stages = []
    for stage in stage_outputs:
        if isinstance(stage, dict) and stage.get("_simulated"):
            simulated_stages.append(stage.get("_stage_name", "unknown"))
    is_simulated = len(simulated_stages) > 0
    return {
        "is_simulated": is_simulated,
        "simulated_stages": simulated_stages,
        "simulation_notice": SIMULATION_NOTICE if is_simulated else None
    }

def _strip_json_fences(text: str) -> str:
    """Claude on Bedrock has no strict JSON-mode flag (unlike Groq's response_format) — it reliably
    wraps JSON in ```json ... ``` markdown fences despite instructions not to. Strip them before parsing."""
    text = text.strip()
    if text.startswith("```"):
        text = re.sub(r"^```(?:json)?\s*", "", text)
        text = re.sub(r"\s*```$", "", text)
    return text.strip()

def call_bedrock_json(prompt: str, system_instruction: str = "") -> Dict[str, Any]:
    """Helper to call AWS Bedrock (Claude) with a prompt and force a JSON response."""
    global bedrock_client
    if not is_api_key_valid():
        raise ValueError("Invalid AWS Bedrock credentials")

    if bedrock_client is None:
        _init_bedrock_client()
    if bedrock_client is None:
        raise ValueError("Failed to initialize AWS Bedrock client")

    system_text = (
        (system_instruction + "\n\n" if system_instruction else "") +
        "Respond with ONLY a single valid JSON object. Do not include any explanation, "
        "markdown code fences, or text outside the JSON object."
    )

    try:
        response = bedrock_client.converse(
            modelId=BEDROCK_MODEL_ID,
            system=[{"text": system_text}],
            messages=[{"role": "user", "content": [{"text": prompt}]}],
            # 4096 was truncating the largest schemas (internal bid analysis, client proposal) before
            # they finished generating valid JSON, causing needless fallbacks to mock data.
            inferenceConfig={"maxTokens": 8192, "temperature": 0.2}
        )
        content = response["output"]["message"]["content"][0]["text"]
        cleaned = _strip_json_fences(content)

        # Debug logging to file
        log_file = os.path.join(os.path.dirname(os.path.abspath(__file__)), "bedrock_debug.log")
        with open(log_file, "a", encoding="utf-8") as lf:
            lf.write("\n==================================================\n")
            lf.write(f"SYSTEM: {system_text}\n")
            lf.write(f"PROMPT: {prompt}\n")
            lf.write(f"RESPONSE: {content}\n")
            lf.write("==================================================\n")

        return json.loads(cleaned)
    except Exception as e:
        log_file = os.path.join(os.path.dirname(os.path.abspath(__file__)), "bedrock_debug.log")
        with open(log_file, "a", encoding="utf-8") as lf:
            lf.write("\n==================================================\n")
            lf.write(f"ERROR: {e}\n")
            lf.write(f"PROMPT: {prompt}\n")
            lf.write("==================================================\n")
        print(f"Error calling AWS Bedrock API: {e}")
        traceback.print_exc()
        raise e

def split_sows_if_multiple(email_text: str) -> List[str]:
    """Uses the LLM to separate an email containing multiple SOW descriptions into individual project texts."""
    system_instruction = (
        "You are an expert SOW separator. Read the provided email text and determine if it contains descriptions "
        "for multiple independent projects or statements of work (SOWs).\n"
        "Respond with a JSON object matching this structure:\n"
        "{\n"
        "  \"sows\": [\"project 1 text description here\", \"project 2 text description here\"]\n"
        "}\n\n"
        "If it describes only one project, return the original text as the single element in the 'sows' list."
    )
    
    prompt = f"Examine this email text and separate into individual SOWs if there are multiple:\n\n{email_text}"
    
    try:
        # If credentials are valid, call the LLM
        if is_api_key_valid():
            res = call_bedrock_json(prompt, system_instruction)
            if isinstance(res, dict) and "sows" in res:
                return res["sows"]
            elif isinstance(res, dict) and "projects" in res:
                return res["projects"]
            elif isinstance(res, list):
                return res
        return [email_text]
    except Exception as e:
        print(f"Error splitting SOWs: {e}")
        return [email_text]

