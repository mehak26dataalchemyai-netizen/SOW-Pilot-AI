def generate_clarifying_questions(requirements: Dict[str, Any]) -> Dict[str, Any]:
    """Drafts questions to send back to the client about anything ambiguous or missing in the SOW,
    before committing to a full solution/resourcing/pricing plan built on guesses."""
    system_instruction = (
        "You are an expert Bid Manager preparing pre-bid clarification questions for a client, based on gaps or "
        "ambiguities in their SOW/RFP. Only ask about things that are genuinely unclear, missing, or contradictory "
        "in the provided requirements — do not ask generic filler questions.\n"
        "Look specifically for: vague or missing budget, deliverables described without acceptance criteria, "
        "missing technical constraints, unclear dependencies on the client's side, ambiguous deadlines, and "
        "unclear scope boundaries.\n"
        "Respond with a JSON object matching this structure:\n"
        "{\n"
        "  \"questions\": [\"Specific, concrete question 1\", \"Specific, concrete question 2\"]\n"
        "}\n"
        "If the requirements are already clear and complete, return an empty list — do not invent questions just to have some."
    )

    prompt = f"Review these extracted SOW requirements and draft pre-bid clarifying questions:\n\n{json.dumps(requirements, indent=2)}"

    try:
        result = call_bedrock_json(prompt, system_instruction)
        if isinstance(result, dict) and "questions" in result:
            result["_simulated"] = False
            result["_stage_name"] = "Pre-Bid Questions"
            return result
        raise ValueError("Invalid JSON structure returned by LLM")
    except Exception as e:
        print("Using Pre-Bid Questions Mock Fallback due to error.")
        fallback_questions = []
        if not requirements.get("budget") or requirements.get("budget") == "Not specified":
            fallback_questions.append("Could you confirm the approved budget range for this engagement?")
        if not requirements.get("submission_deadline"):
            fallback_questions.append("Could you confirm the exact proposal submission deadline?")
        if not requirements.get("deliverables"):
            fallback_questions.append("Could you clarify the specific deliverables and their acceptance criteria?")
        if not fallback_questions:
            fallback_questions.append("Are there any additional constraints or success criteria not captured in the SOW?")
        return {
            "_simulated": True,
            "_stage_name": "Pre-Bid Questions",
            "questions": fallback_questions
        }

def merge_requirements_with_answers(
    requirements_v1: Dict[str, Any],
    qa_pairs: List[Dict[str, str]],
    exempted_certifications: List[str] = None
) -> Dict[str, Any]:
    """Deterministically produces requirements_v2 by layering the client's pre-bid answers onto v1 —
    v1 is never mutated or overwritten, so both versions remain independently auditable.
    exempted_certifications accumulates any certification gaps the client has explicitly waived across
    all fetched replies so far, so re-qualification can exclude them from missing_certifications."""
    requirements_v2 = json.loads(json.dumps(requirements_v1))  # deep copy
    requirements_v2["clarifications"] = qa_pairs
    requirements_v2["exempted_certifications"] = exempted_certifications or []
    requirements_v2["_derived_from_version"] = 1
    requirements_v2["_stage_name"] = "Requirements (v2 — post pre-bid Q&A)"
    return requirements_v2

