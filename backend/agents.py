def evaluate_extraction_faithfulness(raw_sow_text: str, requirements: Dict[str, Any]) -> Dict[str, Any]:
    """LLM-judge check: does the extracted requirements JSON only contain facts actually present in the
    source SOW text? Replaces a prior placeholder formula that scored higher the more fields were
    extracted (regardless of accuracy) — this instead flags invented numbers, deadlines, or requirements
    not grounded in the source, the way a real faithfulness/groundedness eval should."""
    if not raw_sow_text or not raw_sow_text.strip():
        return {"score": 0, "reasoning": "No source SOW text was available to check extraction against."}

    # Cap the source text sent to the judge — long SOWs don't need the full document to catch
    # hallucinated extraction, and keeping the judge call cheap/fast matters since it runs on every ingest.
    source_excerpt = raw_sow_text[:12000]

    system_instruction = (
        "You are a faithfulness auditor comparing an extracted requirements JSON against the original "
        "source document it was extracted from. Your job is to catch hallucination — any number, date, "
        "requirement, deliverable, or constraint in the JSON that is NOT actually stated or clearly "
        "implied in the source text.\n\n"
        "Score 0-100: 100 means every fact in the JSON is grounded in the source; lower scores mean more "
        "invented content. Respond with a JSON object:\n"
        "{\n"
        "  \"score\": <integer 0-100>,\n"
        "  \"hallucinated_fields\": [\"short description of each invented fact found, empty list if none\"],\n"
        "  \"reasoning\": \"one or two sentences explaining the score\"\n"
        "}"
    )
    combined_inputs = {"source_text": source_excerpt, "extracted_requirements": requirements}
    result = call_bedrock_json(f"Source and extraction to compare:\n{json.dumps(combined_inputs)}", system_instruction)

    score = result.get("score")
    if not isinstance(score, (int, float)):
        score = 70  # neutral fallback if the judge call failed to parse, not a fabricated high score
    return {
        "score": max(0, min(100, int(score))),
        "hallucinated_fields": result.get("hallucinated_fields") or [],
        "reasoning": result.get("reasoning") or "Faithfulness check completed.",
    }

