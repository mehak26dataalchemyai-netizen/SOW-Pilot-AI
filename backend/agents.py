def match_answers_to_questions(reply_text: str, pending_questions: List[str]) -> Dict[str, Any]:
    """Reads a client's free-form email reply and matches its content back to the specific pending
    pre-bid questions it answers. This genuinely needs interpretation (the client won't reply with a
    clean numbered list matching our exact question order), so unlike qualify_bid this IS an LLM call.
    Also flags whether any answer explicitly grants a certification exemption/equivalent, since our
    auto-generated cert-gap questions specifically ask for that. Only returns matches the model is
    actually confident about — anything ambiguous is left unmatched for a human to review manually."""
    if not reply_text or not pending_questions:
        return {"_simulated": False, "matches": [], "exempted_certifications": []}

    system_instruction = (
        "You are matching a client's email reply to a list of specific pending questions we asked them. "
        "For each question that the reply clearly answers, extract the relevant answer text (quote or "
        "closely paraphrase the client's own words — do not invent details they didn't provide). "
        "If the reply does not address a question, or only vaguely touches it, do NOT include it — "
        "leaving it unmatched is better than guessing.\n"
        "Separately, identify if the client explicitly agrees to accept an equivalent certification, grants "
        "an exemption, or waives a certification requirement for any named certification — list those "
        "certification names in exempted_certifications (use the exact certification name as it appears "
        "in the question being answered, if identifiable).\n"
        "Respond with a JSON object matching this structure:\n"
        "{\n"
        "  \"matches\": [\n"
        "    {\"question\": \"The exact pending question text this answers (copy verbatim from the list given)\", \"answer\": \"Extracted answer text\"}\n"
        "  ],\n"
        "  \"exempted_certifications\": [\"Certification name the client agreed to waive/accept an equivalent for\"]\n"
        "}"
    )

    prompt = (
        f"Pending questions:\n" + "\n".join(f"- {q}" for q in pending_questions) +
        f"\n\nClient's reply email:\n{reply_text}"
    )

    try:
        result = call_bedrock_json(prompt, system_instruction)
        matches = result.get("matches", []) if isinstance(result, dict) else []
        exempted = result.get("exempted_certifications", []) if isinstance(result, dict) else []
        # Only keep matches whose question text actually corresponds to one we asked — guards against
        # the model paraphrasing the question so loosely it no longer maps back to a real DB row.
        valid_matches = [m for m in matches if m.get("question") in pending_questions and m.get("answer")]
        return {"_simulated": False, "matches": valid_matches, "exempted_certifications": exempted}
    except Exception as e:
        print(f"[ANSWER MATCHING] Failed to match reply to pending questions: {e}")
        return {"_simulated": True, "matches": [], "exempted_certifications": []}

def classify_proposal_response(reply_text: str) -> Dict[str, Any]:
    """Reads a client's free-form email reply to a sent proposal and classifies it — did they accept,
    reject, or come back with changes? This genuinely needs interpretation (real replies are prose, not
    a clean "ACCEPT" or "REJECT" keyword), so it's an LLM call, same reasoning as match_answers_to_questions.
    Returns a classification only — a human still confirms the Win/Loss record or starts a revision round;
    this never writes directly to project state."""
    if not reply_text or not reply_text.strip():
        return {"response_type": "Unclear", "summary": "", "requested_changes": []}

    system_instruction = (
        "You are reading a client's email reply to a business proposal. Classify their response and "
        "summarize it concisely and factually — do not add interpretation beyond what's actually written.\n"
        "Respond with a JSON object matching this structure:\n"
        "{\n"
        "  \"response_type\": \"Accepted\" | \"Rejected\" | \"Revision Requested\" | \"Unclear\",\n"
        "  \"summary\": \"one or two sentence factual summary of what the client said\",\n"
        "  \"requested_changes\": [\"each distinct change or term the client asked for, as its own short "
        "item, close to their own wording — empty list if none were requested\"]\n"
        "}\n"
        "Use \"Revision Requested\" when the client raises questions, asks for different pricing/scope/"
        "timeline, or otherwise doesn't give a clean yes/no. Use \"Unclear\" only if the reply genuinely "
        "doesn't indicate any of the other three. List each ask SEPARATELY in requested_changes — do not "
        "merge multiple asks into one string — so each one can be reviewed and decided on individually."
    )
    result = call_bedrock_json(f"Client's email reply to our proposal:\n{reply_text}", system_instruction)
    changes = result.get("requested_changes") or []
    if isinstance(changes, str):
        changes = [changes] if changes.strip() else []
    return {
        "response_type": result.get("response_type") or "Unclear",
        "summary": result.get("summary") or "",
        "requested_changes": changes,
    }

