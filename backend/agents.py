from datetime import datetime, date
import re as _re

def _try_parse_deadline(text: str):
    """Best-effort parse of a free-text deadline string into a date. Returns None if unparseable —
    we never guess a date that wasn't actually stated."""
    if not text or not isinstance(text, str):
        return None
    text = text.strip()

    # Deadlines are frequently stated with a trailing time-of-day and timezone (e.g. "October 24, 2026,
    # 5:00 PM ET") — the day/month/year is what matters for a feasibility check, so strip that clause
    # before attempting a plain-date format rather than giving up on the whole string. The colon in
    # "H:MM" is required here (not optional) so this never matches a bare trailing year like "2026".
    stripped = _re.sub(
        r"(?:,|\s+at)?\s*\d{1,2}:\d{2}\s*(?:[AaPp]\.?[Mm]\.?)?\s*(?:[A-Za-z]{2,5}\.?)?\s*$", "", text
    ).strip().rstrip(",").strip()
    candidates = [text] if stripped == text or not stripped else [stripped, text]

    formats = [
        "%Y-%m-%d", "%m/%d/%Y", "%d/%m/%Y", "%B %d, %Y", "%b %d, %Y",
        "%d %B %Y", "%d %b %Y", "%m-%d-%Y", "%Y/%m/%d"
    ]
    for candidate in candidates:
        for fmt in formats:
            try:
                return datetime.strptime(candidate, fmt).date()
            except ValueError:
                continue

    match = _re.search(r"(20\d{2})[-/](\d{1,2})[-/](\d{1,2})", text)
    if match:
        try:
            return date(int(match.group(1)), int(match.group(2)), int(match.group(3)))
        except ValueError:
            return None
    return None

def qualify_bid(requirements: Dict[str, Any], org_capabilities: List[str] = None, exempted_certifications: List[str] = None) -> Dict[str, Any]:
    """Deterministically evaluates whether this bid should be pursued, based on real, checkable facts:
    whether the deadlines are still reachable and whether the org holds the certifications the RFP
    mandates. This is intentionally NOT an LLM call — a Go/No-Go recommendation should be reproducible
    and auditable, not a guess. Returns a recommendation only; a human still makes the final decision.

    exempted_certifications: certifications the client has explicitly agreed (via a pre-bid answer) to
    waive or accept an equivalent for — excluded from missing_certifications so a resolved gap doesn't
    keep blocking the bid on re-qualification."""
    org_capabilities = org_capabilities or []
    org_caps_lower = {c.lower().strip() for c in org_capabilities}
    exempted_lower = {c.lower().strip() for c in (exempted_certifications or [])}

    def _cert_is_in(cert: str, held_set: set) -> bool:
        """A SOW's required-certification text is often the bare cert name plus extra wording
        (e.g. "ISO 27001 (preferred; equivalent certifications will be considered upon request)")
        rather than exactly matching how it's recorded in org capabilities. An exact-equality check
        would wrongly flag that as missing even though the org genuinely holds ISO 27001 — so a held
        capability counts as satisfied if it appears as a whole-word match within the required text
        (or vice versa). Word-boundary matching (not plain substring) matters here: plain substring
        containment would wrongly treat "SOC 2 Type I" as satisfied by holding "SOC 2 Type II", since
        "type i" is literally a substring of "type ii" — those are different, non-equivalent audit
        standards, and \\b prevents that false match while still catching the ISO 27001 case."""
        cert_lower = cert.lower().strip()
        if cert_lower in held_set:
            return True
        for held in held_set:
            if re.search(r"\b" + re.escape(held) + r"\b", cert_lower):
                return True
            if re.search(r"\b" + re.escape(cert_lower) + r"\b", held):
                return True
        return False

    required_certs = requirements.get("required_certifications") or []
    missing_certs = [
        c for c in required_certs
        if not _cert_is_in(c, org_caps_lower) and not _cert_is_in(c, exempted_lower)
    ]
    newly_exempted = [c for c in required_certs if _cert_is_in(c, exempted_lower) and not _cert_is_in(c, org_caps_lower)]

    today = date.today()
    reasoning = []
    blocking_issues = []

    submission_deadline_raw = requirements.get("submission_deadline")
    submission_deadline = _try_parse_deadline(submission_deadline_raw) if submission_deadline_raw else None
    deadline_status = "unknown"
    if submission_deadline_raw and not submission_deadline:
        deadline_status = "unparseable"
        reasoning.append(f"Submission deadline recorded as '{submission_deadline_raw}'; please confirm feasibility against today's date during final review.")
    elif submission_deadline:
        days_remaining = (submission_deadline - today).days
        if days_remaining < 0:
            deadline_status = "passed"
            blocking_issues.append(f"Submission deadline ({submission_deadline_raw}) has already passed.")
        elif days_remaining <= 3:
            deadline_status = "critical"
            reasoning.append(f"Only {days_remaining} day(s) left until the submission deadline — high time pressure.")
        else:
            deadline_status = "reachable"
            reasoning.append(f"{days_remaining} day(s) remain until the submission deadline — reachable.")
    else:
        reasoning.append("No submission deadline was stated in the document — cannot assess time pressure.")

    if newly_exempted:
        reasoning.append(f"Client has granted an exemption/equivalent for: {', '.join(newly_exempted)}.")

    if missing_certs:
        blocking_issues.append(f"Missing {len(missing_certs)} required certification(s): {', '.join(missing_certs)}.")
    elif required_certs:
        reasoning.append(f"All {len(required_certs)} required certification(s) are held or exempted.")
    else:
        reasoning.append("No mandatory certifications were stated in the document.")

    if blocking_issues:
        recommendation = "No-Go"
    elif deadline_status == "critical" or deadline_status == "unparseable":
        recommendation = "Caution"
    else:
        recommendation = "Go"

    return {
        "_simulated": False,
        "_stage_name": "Bid Qualification",
        "recommendation": recommendation,
        "blocking_issues": blocking_issues,
        "reasoning": reasoning,
        "required_certifications": required_certs,
        "missing_certifications": missing_certs,
        "exempted_certifications": newly_exempted,
        "submission_deadline": submission_deadline_raw,
        "pre_bid_question_deadline": requirements.get("pre_bid_question_deadline"),
        "deadline_status": deadline_status
    }

