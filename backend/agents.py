def match_worker_to_task(task_text: str, workers: List[Dict[str, Any]]) -> Dict[str, Any]:
    """Uses LLM to evaluate the match score and reasons for a list of workers against a task."""
    system_instruction = (
        "You are an expert Talent Allocation Officer. Analyze the given project task description against the list of "
        "available workers (roles and skills). Conceptually evaluate the suitability of each worker for the task.\n\n"
        "Evaluation criteria:\n"
        "- Experience alignment: Does their role fit the task context (e.g. cloud -> DevOps, visual -> Frontend)?\n"
        "- Skills match: Do they have direct skills or conceptually related skills (e.g. PyPDF -> Python, Docker -> ECS)?\n"
        "- Synonyms and conceptual overlap: Understand synonyms. For example, 'deploy on server' aligns conceptually with DevOps, "
        "even if the exact words do not match.\n\n"
        "Provide a score between 0 and 100 for each worker. If a worker has zero match, assign a score of 0.\n"
        "Provide 1-2 concrete, concise reasons explaining the match or lack thereof.\n\n"
        "Respond with a JSON object matching this structure:\n"
        "{\n"
        "  \"matches\": [\n"
        "    {\n"
        "      \"worker_id\": \"id of the worker\",\n"
        "      \"score\": 85,\n"
        "      \"reasons\": [\"Role matches requirements\", \"Has required skill...\"]\n"
        "    }\n"
        "  ]\n"
        "}"
    )

    user_prompt = f"Task Description: \"{task_text}\"\n\nWorkers List:\n{json.dumps(workers, indent=2)}"

    try:
        if not is_api_key_valid():
            raise ValueError("Invalid AWS Bedrock credentials")

        res = call_bedrock_json(prompt=user_prompt, system_instruction=system_instruction)
        if isinstance(res, dict) and "matches" in res:
            res["_simulated"] = False
            return res
        raise ValueError("Invalid JSON structure returned by LLM")
    except Exception as e:
        print(f"[SEMANTIC MATCH AGENT FALLBACK] Using local semantic heuristic: {e}")
        
        # Local heuristic fallback matching engine
        matches = []
        task_lower = task_text.lower()
        
        for w in workers:
            w_id = w.get("id", "")
            role = w.get("role", "").lower()
            skills = w.get("skills", [])
            score = 0
            reasons = []
            
            # Role mapping
            if any(k in task_lower for k in ["frontend", "ui", "ux", "dashboard", "react", "visual", "chart", "page", "html", "css"]):
                if any(r in role for r in ["frontend", "designer", "ux", "ui", "developer"]):
                    score += 50
                    reasons.append("Role aligns with UI/Frontend tasks")
            if any(k in task_lower for k in ["backend", "fastapi", "python", "langgraph", "api", "sse", "server", "database", "sql", "postgres"]):
                if any(r in role for r in ["backend", "ai", "engineer", "database", "dba"]):
                    score += 50
                    reasons.append("Role aligns with Backend/Data tasks")
            if any(k in task_lower for k in ["devops", "deploy", "aws", "docker", "vpc", "cloud", "hosting", "ci/cd", "github actions"]):
                if any(r in role for r in ["devops", "cloud", "engineer"]):
                    score += 50
                    reasons.append("Role aligns with DevOps/Deployment tasks")
            if any(k in task_lower for k in ["test", "qa", "automation", "audit", "soc 2", "compliance", "verification"]):
                if any(r in role for r in ["qa", "test", "security", "compliance"]):
                    score += 50
                    reasons.append("Role aligns with QA/Security/Compliance tasks")
            if any(k in task_lower for k in ["project", "manage", "timeline", "sprint", "kickoff", "plan", "document", "analyst", "client"]):
                if any(r in role for r in ["manager", "scrum", "owner", "analyst", "writer"]):
                    score += 50
                    reasons.append("Role aligns with Project Planning/Management tasks")
            
            # Skill mapping
            for skill in skills:
                s = skill.lower()
                if s in task_lower or task_lower in s:
                    score += 30
                    reasons.append(f"Matching competency: {skill}")
                else:
                    skill_words = s.split()
                    matched_words = [word for word in skill_words if len(word) > 2 and word in task_lower]
                    if matched_words:
                        score += 20 * len(matched_words)
                        reasons.append(f"Related competency: {skill}")
            
            final_score = min(score, 100)
            if final_score > 0:
                matches.append({
                    "worker_id": w_id,
                    "score": final_score,
                    "reasons": reasons[:2]
                })
            else:
                matches.append({
                    "worker_id": w_id,
                    "score": 0,
                    "reasons": ["Role/skills do not align with task"]
                })
                
        return {"matches": matches, "_simulated": True}
